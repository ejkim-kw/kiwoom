/* Shared, data-only presentation configuration. No editor UI or storage. */
(function(root,factory){
  const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;
  root.KiwoomContentModel=api;
})(typeof globalThis!=='undefined'?globalThis:this,function(){
  const empty=()=>({version:1,categoryOrder:[],itemOrder:{},labels:{},copies:[]});
  const clone=value=>JSON.parse(JSON.stringify(value));
  const object=value=>value&&typeof value==='object'&&!Array.isArray(value);
  const safeKey=key=>!['__proto__','prototype','constructor'].includes(key);
  function fail(message){throw new Error(message);}
  function text(value,name,max=2000,blank=false){
    if(typeof value!=='string'||value.length>max||(!blank&&!value.trim())||/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/.test(value))fail(`${name} 형식을 확인해 주세요.`);
    return value;
  }
  function order(value,ids,name,allowEmpty=false){
    if(!Array.isArray(value)||value.some(id=>typeof id!=='string'))fail(`${name} 순서가 올바르지 않아요.`);
    if(allowEmpty&&!value.length)return [];
    if(value.length!==ids.length||new Set(value).size!==ids.length||value.some(id=>!ids.includes(id)))fail(`${name}에는 기존 메뉴가 한 번씩 포함되어야 해요.`);
    return [...value];
  }
  function labelKeys(catalog){
    return new Set([
      ...catalog.categories.flatMap(c=>[`category:${c.id}:title`,`category:${c.id}:subtitle`]),
      ...[...catalog.categories.flatMap(c=>c.items),...catalog.legacyItems,...catalog.otherDocuments,...catalog.selfServices].map(i=>`item:${i.id}:title`)
    ]);
  }
  function validate(value,catalog){
    if(!object(value)||value.version!==1)fail('지원하는 편집 파일 형식이 아니에요.');
    const result=empty(),keys=labelKeys(catalog);
    for(const key of Object.keys(value))if(!Object.hasOwn(result,key))fail('알 수 없는 편집 항목이에요.');
    result.categoryOrder=order(value.categoryOrder,catalog.categories.map(c=>String(c.id)),'대메뉴',true);
    if(!object(value.itemOrder)||!object(value.labels)||!Array.isArray(value.copies))fail('편집 데이터가 올바르지 않아요.');
    for(const [id,ids] of Object.entries(value.itemOrder)){
      const category=catalog.categories.find(c=>String(c.id)===id);
      if(!safeKey(id)||!category)fail('알 수 없는 대메뉴예요.');
      result.itemOrder[id]=order(ids,category.items.map(i=>i.id),category.title);
    }
    for(const [key,label] of Object.entries(value.labels)){
      if(!safeKey(key)||!keys.has(key))fail('변경할 수 없는 메뉴 항목이에요.');
      result.labels[key]=text(label,'메뉴 문구',120,key.endsWith(':subtitle'));
    }
    if(value.copies.length>1000)fail('문구 변경은 한 파일에 1,000개까지 저장할 수 있어요.');
    const seen=new Set();
    result.copies=value.copies.map(copy=>{
      if(!object(copy)||Object.keys(copy).some(k=>!['scope','root','selector','original','text'].includes(k)))fail('문구 변경 형식이 올바르지 않아요.');
      const scope=text(copy.scope,'화면',800),root=text(copy.root,'화면 영역',80),selector=text(copy.selector,'문구 위치',1600);
      if(!/^[A-Za-z][\w-]*$/.test(root)||['body','html'].includes(root))fail('휴대폰 화면 안의 문구만 변경할 수 있어요.');
      if(/(^|[>+~\s])(input|textarea|select|script|style|iframe|object|embed)(?=$|[.#\[:>+~\s])/i.test(selector)||/[{},]/.test(selector))fail('입력값이나 실행 요소는 변경할 수 없어요.');
      const key=scope+'\n'+root+'\n'+selector;if(seen.has(key))fail('같은 문구 변경이 중복되어 있어요.');seen.add(key);
      return {scope,root,selector,original:text(copy.original,'기존 문구'),text:text(copy.text,'변경 문구',2000,true)};
    });
    return result;
  }
  function applyCatalog(catalog,data){
    const result=clone(catalog),ordered=(items,ids)=>ids?.length?ids.map(id=>items.find(i=>String(i.id)===id)):items;
    result.categories=ordered(result.categories,data.categoryOrder);
    result.categories.forEach(category=>{
      for(const field of ['title','subtitle'])category[field]=data.labels[`category:${category.id}:${field}`]??category[field];
      category.items=ordered(category.items,data.itemOrder[category.id]);
    });
    [...result.categories.flatMap(c=>c.items),...result.legacyItems,...result.otherDocuments,...result.selfServices].forEach(item=>{
      item.title=data.labels[`item:${item.id}:title`]??item.title;
    });
    return result;
  }
  function move(ids,id,target){
    if(!ids.includes(id)||!ids.includes(target))fail('이동할 메뉴를 찾지 못했어요.');
    const next=[...ids],index=next.indexOf(target);next.splice(next.indexOf(id),1);next.splice(index,0,id);return next;
  }
  function toScript(data){
    const json=JSON.stringify(data,null,2).replace(/</g,'\\u003c').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029');
    return `/* Published presentation edits. Generated by npm run apply:content. */\n(function(root){const data=${json};root.KiwoomContentData=data;if(typeof module==='object'&&module.exports)module.exports=data;})(typeof globalThis!=='undefined'?globalThis:this);\n`;
  }
  return {empty,clone,validate,applyCatalog,move,toScript};
});
